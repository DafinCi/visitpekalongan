// Helper pembuat jadwal standar harian
function makeDailySchedule(
  open: string,
  close: string,
  closedDays: string[] = []
): WeeklyOpeningHours {
  const days = [
    "monday",
    "tuesday",
    "wednesday",
    "thursday",
    "friday",
    "saturday",
    "sunday",
  ] as const;

  const result = {} as WeeklyOpeningHours;

  for (const day of days) {
    if (closedDays.includes(day)) {
      result[day] = { slots: [], is_closed: true };
    } else {
      result[day] = {
        slots: [{ open, close }],
        is_closed: false,
      };
    }
  }

  return result;
}

// Jumat dipecah menjadi dua slot agar tabel dan status memakai jadwal yang sama
function makeScheduleWithFridayBreak(
  open: string,
  close: string
): WeeklyOpeningHours {
  const schedule = makeDailySchedule(open, close);
  const fridaySlots: TimeSlot[] = [];

  if (open < "11:15" && close > "11:15") {
    fridaySlots.push({ open, close: "11:15" });
  }
  if (close > "13:00") {
    fridaySlots.push({ open: "13:00", close });
  }

  schedule.friday = {
    slots: fridaySlots.length > 0 ? fridaySlots : [{ open, close }],
    is_closed: false,
  };
  schedule.notes =
    "Jumat tutup sejenak pukul 11:15 hingga 13:00 untuk ibadah salat Jumat";
  return schedule;
}

